from abc import ABC, abstractmethod
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field
import structlog

logger = structlog.get_logger(__name__)


class RubricResult(BaseModel):
    """Standardized result from rubric evaluation."""
    passed: bool = Field(..., description="Whether the evaluation passed the rubric criteria")
    confidence_score: float = Field(..., ge=0.0, le=1.0, description="Confidence in the evaluation result")
    reasoning: str = Field(..., description="Explanation of why the result was determined")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Additional rubric-specific metadata")


class BaseRubric(ABC):
    """Abstract base class for all evaluation rubrics.
    
    Rubrics evaluate LLM outputs against specific criteria such as format,
    content, tone, or grounding. Each rubric implements its own evaluation logic
    while providing a standardized result structure.
    """

    def __init__(self, config: Optional[Dict[str, Any]] = None):
        self.config = config or {}
        self.rubric_name = self.__class__.__name__.replace("Check", "")

    @abstractmethod
    async def evaluate(
        self,
        generated_text: str,
        expected_behavior: Dict[str, Any],
        context: Optional[Dict[str, Any]] = None,
    ) -> RubricResult:
        """Evaluate generated text against the rubric criteria.
        
        Args:
            generated_text: The text generated by the LLM
            expected_behavior: Expected behavior/criteria from the evaluation case
            context: Additional context for evaluation (e.g., input prompt, metadata)
            
        Returns:
            RubricResult: Standardized evaluation result
        """
        pass

    @abstractmethod
    def get_description(self) -> str:
        """Get a human-readable description of this rubric.
        
        Returns:
            str: Description of what this rubric evaluates
        """
        pass

    async def evaluate_with_logging(
        self,
        generated_text: str,
        expected_behavior: Dict[str, Any],
        context: Optional[Dict[str, Any]] = None,
    ) -> RubricResult:
        """Evaluate with structured logging.
        
        This wrapper method adds logging around the evaluation for observability.
        """
        await logger.adebug(
            "Rubric evaluation started",
            rubric=self.rubric_name,
            text_length=len(generated_text),
        )

        result = await self.evaluate(generated_text, expected_behavior, context)

        await logger.adebug(
            "Rubric evaluation completed",
            rubric=self.rubric_name,
            passed=result.passed,
            confidence=result.confidence_score,
        )

        return result
